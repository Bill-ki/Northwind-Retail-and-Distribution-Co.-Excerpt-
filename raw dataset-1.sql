DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS inventory_transactions CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS suppliers CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS departments CASCADE;

CREATE TABLE departments (
    department_id   SERIAL PRIMARY KEY,
    department_name VARCHAR(50) NOT NULL,
    budget          NUMERIC(12,2)
);

CREATE TABLE employees (
    employee_id     SERIAL PRIMARY KEY,
    first_name      VARCHAR(50) NOT NULL,
    last_name       VARCHAR(50) NOT NULL,
    email           VARCHAR(100),
    department_id   INT REFERENCES departments(department_id),
    manager_id      INT REFERENCES employees(employee_id),
    job_title       VARCHAR(50),
    hire_date       DATE NOT NULL,
    salary          NUMERIC(10,2) NOT NULL,
    region          VARCHAR(30)
);

CREATE TABLE customers (
    customer_id     SERIAL PRIMARY KEY,
    company_name    VARCHAR(100) NOT NULL,
    contact_name    VARCHAR(100),
    email           VARCHAR(100),
    country         VARCHAR(50),
    city            VARCHAR(50),
    segment         VARCHAR(20),          -- Consumer / Corporate / Small Business
    signup_date     DATE
);

CREATE TABLE suppliers (
    supplier_id     SERIAL PRIMARY KEY,
    supplier_name   VARCHAR(100) NOT NULL,
    country         VARCHAR(50),
    lead_time_days  INT,                  -- avg days to deliver
    rating          NUMERIC(3,2)          -- 0-5 supplier quality rating
);

CREATE TABLE categories (
    category_id     SERIAL PRIMARY KEY,
    category_name   VARCHAR(50) NOT NULL
);

CREATE TABLE products (
    product_id      SERIAL PRIMARY KEY,
    product_name    VARCHAR(100) NOT NULL,
    category_id     INT REFERENCES categories(category_id),
    supplier_id     INT REFERENCES suppliers(supplier_id),
    unit_cost       NUMERIC(10,2) NOT NULL,   -- what we pay supplier
    unit_price      NUMERIC(10,2) NOT NULL,   -- what we sell for
    stock_quantity  INT NOT NULL,
    reorder_level   INT NOT NULL,
    discontinued    BOOLEAN DEFAULT FALSE
);

CREATE TABLE orders (
    order_id        SERIAL PRIMARY KEY,
    customer_id     INT REFERENCES customers(customer_id),
    employee_id     INT REFERENCES employees(employee_id),
    order_date      DATE NOT NULL,
    ship_date       DATE,
    status          VARCHAR(20) NOT NULL,   -- Pending/Shipped/Delivered/Cancelled/Returned
    ship_region     VARCHAR(30)
);

CREATE TABLE order_items (
    order_item_id   SERIAL PRIMARY KEY,
    order_id        INT REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id      INT REFERENCES products(product_id),
    quantity        INT NOT NULL,
    unit_price      NUMERIC(10,2) NOT NULL,   -- price at time of sale
    discount        NUMERIC(4,2) DEFAULT 0    -- e.g. 0.10 = 10%
);

CREATE TABLE payments (
    payment_id      SERIAL PRIMARY KEY,
    order_id        INT REFERENCES orders(order_id) ON DELETE CASCADE,
    payment_date    DATE,
    amount          NUMERIC(10,2) NOT NULL,
    method          VARCHAR(20),            -- Credit Card/Bank Transfer/PayPal/Check
    status          VARCHAR(20)             -- Completed/Failed/Refunded/Pending
);

CREATE TABLE inventory_transactions (
    transaction_id   SERIAL PRIMARY KEY,
    product_id       INT REFERENCES products(product_id),
    transaction_date DATE NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,  -- Restock/Sale/Return/Adjustment/Damaged
    quantity         INT NOT NULL           -- positive = in, negative = out
);

